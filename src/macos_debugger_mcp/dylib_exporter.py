"""Standalone ARM64 Dylib Patch Generator and Clang Compiler for macOS/PlayCover."""

from __future__ import annotations

import os
import subprocess
from typing import Any, Dict, List, Union


def export_dylib_patch(
    patch_name: str,
    target_framework: str,
    patches: List[Dict[str, Any]],
    output_dir: str = "/Users/alfaroo/Sintax/MCP/macos-debugger-mcp/dist_patches",
) -> Dict[str, Any]:
    """Generate and compile a standalone ARM64 C dylib to hook/patch memory offsets.

    Args:
        patch_name: Name of the generated patch (e.g. 'InfiniteBirdsPatch').
        target_framework: Name of target framework or binary (e.g. 'UnityFramework').
        patches: List of patch items, each containing 'offset', 'patch_bytes', and optional 'description'.
        output_dir: Output directory to place source code and compiled .dylib.
    """
    if not patches:
        raise ValueError("Patches list cannot be empty")

    out_path = os.path.expanduser(output_dir)
    os.makedirs(out_path, exist_ok=True)

    # Process and sanitize patch definitions
    processed_patches = []
    for idx, p in enumerate(patches):
        raw_off = p.get("offset")
        if isinstance(raw_off, str):
            off_val = int(raw_off, 16) if raw_off.lower().startswith("0x") else int(raw_off)
        else:
            off_val = int(raw_off)

        raw_bytes = p.get("patch_bytes", "").strip().replace(" ", "").replace("0x", "")
        byte_data = bytes.fromhex(raw_bytes)
        desc = p.get("description", f"Patch #{idx + 1}")

        c_hex_bytes = ", ".join(f"0x{b:02x}" for b in byte_data)

        processed_patches.append({
            "offset_hex": f"0x{off_val:x}",
            "byte_len": len(byte_data),
            "c_hex_bytes": c_hex_bytes,
            "description": desc,
        })

    # Generate patch.c
    c_source = f"""// Generated by macos-debugger-mcp: Standalone ARM64 Dylib Patch
// Target Framework: {target_framework}
// Patch Name: {patch_name}

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>
#include <mach/mach.h>
#include <mach-o/dyld.h>
#include <libkern/OSCacheControl.h>

typedef struct {{
    uintptr_t offset;
    const uint8_t *bytes;
    size_t length;
    const char *description;
}} PatchEntry;

static uintptr_t get_framework_base(const char *framework_name) {{
    uint32_t count = _dyld_image_count();
    for (uint32_t i = 0; i < count; i++) {{
        const char *img_name = _dyld_get_image_name(i);
        if (img_name && strstr(img_name, framework_name)) {{
            return (uintptr_t)_dyld_get_image_header(i);
        }}
    }}
    return 0;
}}

static int apply_patch(uintptr_t target_addr, const uint8_t *patch_bytes, size_t length) {{
    long page_size = sysconf(_SC_PAGESIZE);
    uintptr_t page_start = target_addr & ~(page_size - 1);
    vm_size_t total_size = ((target_addr + length - page_start + page_size - 1) / page_size) * page_size;

    kern_return_t kr = vm_protect(mach_task_self(), page_start, total_size, FALSE, VM_PROT_READ | VM_PROT_WRITE | VM_PROT_COPY);
    if (kr != KERN_SUCCESS) {{
        printf("[Patch] Failed to set page RW: kr = %d\\n", kr);
        return -1;
    }}

    memcpy((void*)target_addr, patch_bytes, length);

    kr = vm_protect(mach_task_self(), page_start, total_size, FALSE, VM_PROT_READ | VM_PROT_EXECUTE);
    if (kr != KERN_SUCCESS) {{
        printf("[Patch] Failed to restore page RX: kr = %d\\n", kr);
        return -1;
    }}

    // Invalidate ARM64 instruction cache
    sys_icache_invalidate((void*)target_addr, length);
    return 0;
}}

__attribute__((constructor))
static void init_{patch_name}(void) {{
    printf("[Patch: {patch_name}] Initializing standalone ARM64 memory patcher...\\n");

    uintptr_t base = get_framework_base("{target_framework}");
    if (!base) {{
        printf("[Patch] Warning: '{target_framework}' not found in loaded images, using ASLR slide or main header\\n");
        base = (uintptr_t)_dyld_get_image_header(0);
    }}

    printf("[Patch] Base address for '{target_framework}': 0x%lx\\n", base);

"""

    for idx, p in enumerate(processed_patches):
        c_source += f"""    // {p['description']}
    static const uint8_t patch_data_{idx}[] = {{ {p['c_hex_bytes']} }};
    uintptr_t addr_{idx} = base + {p['offset_hex']};
    if (apply_patch(addr_{idx}, patch_data_{idx}, {p['byte_len']}) == 0) {{
        printf("[Patch] Applied {p['description']} at 0x%lx\\n", addr_{idx});
    }} else {{
        printf("[Patch] Failed to apply {p['description']} at 0x%lx\\n", addr_{idx});
    }}
"""

    c_source += f"""
    printf("[Patch: {patch_name}] All patches dispatched.\\n");
}}
"""

    c_file_path = os.path.join(out_path, f"{patch_name}.c")
    with open(c_file_path, "w", encoding="utf-8") as f:
        f.write(c_source)

    # Generate Makefile
    makefile_content = f"""CC = clang
CFLAGS = -dynamiclib -arch arm64 -O2 -Wall -fPIC
TARGET = {patch_name}.dylib
SRC = {patch_name}.c

all: $(TARGET)

$(TARGET): $(SRC)
\t$(CC) $(CFLAGS) -o $@ $<

clean:
\trm -f $(TARGET)
"""
    makefile_path = os.path.join(out_path, "Makefile")
    with open(makefile_path, "w", encoding="utf-8") as f:
        f.write(makefile_content)

    # Compile .dylib using clang
    dylib_path = os.path.join(out_path, f"{patch_name}.dylib")
    compile_cmd = [
        "clang",
        "-dynamiclib",
        "-arch",
        "arm64",
        "-O2",
        "-Wall",
        "-fPIC",
        "-o",
        dylib_path,
        c_file_path,
    ]

    proc = subprocess.run(compile_cmd, capture_output=True, text=True)
    if proc.returncode != 0:
        raise RuntimeError(f"Clang compilation failed:\n{proc.stderr}")

    return {
        "status": "success",
        "patch_name": patch_name,
        "dylib_path": dylib_path,
        "source_c_path": c_file_path,
        "makefile_path": makefile_path,
        "total_patches": len(processed_patches),
        "target_framework": target_framework,
    }
